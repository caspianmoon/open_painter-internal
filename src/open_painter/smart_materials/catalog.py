"""Authored, texture-evaluated smart material recipes, ordered bottom to top.

Colors are linear RGB. Metallic colors describe conductor reflectance, not
photographs of shaded metal. Every layer is independent editable texture data;
``surface`` only supplies scalar display parameters on the output material.
Mesh-aware masks deliberately require their corresponding baked maps.
Generated scalar surface inputs add authored grain without supplying lighting,
material color, metalness or mesh-dependent wear.
"""


def surface_detail(source_id, *, scale=(1.0, 1.0), color=0.06,
                   roughness=0.04, height=None):
    """Reference shared scalar pixels with independently editable channel amounts.

    Color is multiplicative around the authored linear color; roughness is an
    additive amount. Height remains centered on 0.5, like procedural relief.
    """
    result = {"id": source_id, "scale": scale, "color": color,
              "roughness": roughness}
    if height is not None:
        result["height"] = height
    return result


def mask(kind, amount=0.35, scale=24.0, *, invert=False, contrast=None,
         procedural=None, generated_source=None, black=None, white=None,
         strength=None, operation=None, seed=None, noise_strength=None,
         uv_scale=None, projection=None, triplanar_hardness=None,
         baked=False, optional=False):
    """``baked`` reads the mesh map named by ``kind`` directly; ``optional``
    masks are skipped, not required, when that map has not been baked."""
    result = {"kind": kind, "amount": amount, "scale": scale}
    if invert:
        result["invert"] = True
    if baked:
        result["baked"] = True
    if optional:
        result["optional"] = True
    if contrast is not None:
        result["contrast"] = contrast
    for key, value in (("procedural", procedural), ("generated_source", generated_source),
                       ("black", black), ("white", white), ("strength", strength),
                       ("operation", operation), ("seed", seed),
                       ("noise_strength", noise_strength), ("uv_scale", uv_scale),
                       ("projection", projection), ("triplanar_hardness", triplanar_hardness)):
        if value is not None:
            result[key] = value
    return result


def layer(name, color, roughness, metallic=0.0, *, procedural=None,
          scale=24.0, detail=0.12, height=None, mask=None, mask_effects=(),
          generated_source=None, channels=None, opacity=None, height_value=None,
          height_range=None, projection=None, triplanar_hardness=None,
          normal_map=None, blend_mode=None):
    """``normal_map`` names a baked mesh map used as the Normal channel image;
    ``blend_mode`` sets the layer blend (for example RNM for normal detail)."""
    result = {"name": name, "color": color, "roughness": roughness,
              "metallic": metallic, "scale": scale, "detail": detail}
    if normal_map:
        result["normal_map"] = normal_map
    if blend_mode:
        result["blend_mode"] = blend_mode
    if procedural:
        result["procedural"] = procedural
    if height is not None:
        result["height"] = height
    if mask:
        result["mask"] = mask
    if mask_effects:
        result["mask_effects"] = list(mask_effects)
    if generated_source:
        result["generated_source"] = generated_source
    if channels is not None:
        result["channels"] = channels
    if opacity is not None:
        result["opacity"] = opacity
    if height_value is not None:
        result["height_value"] = height_value
    for key, value in (("height_range", height_range), ("projection", projection),
                       ("triplanar_hardness", triplanar_hardness)):
        if value is not None:
            result[key] = value
    return result


def recipe(category, description, *layers, surface=None, version=1, modules=()):
    """A catalog entry; ``modules`` nests catalog modules as (name, {layer: {field: value}})."""
    result = {"category": category, "description": description, "layers": list(layers), "version": version}
    if surface:
        result["surface"] = surface
    if modules:
        result["modules"] = list(modules)
    return result


