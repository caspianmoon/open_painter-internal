"""Authored, texture-evaluated smart material recipes, ordered bottom to top.

Colors are linear RGB. Metallic colors describe conductor reflectance, not
photographs of shaded metal. Every layer is independent editable texture data;
``surface`` only supplies scalar display parameters on the output material.
Mesh-aware masks deliberately require their corresponding baked maps.
Generated scalar surface inputs add authored grain without supplying lighting,
material color, metalness or mesh-dependent wear.
"""


def surface_detail(source_id, *, scale=(1.0, 1.0), color=0.06,
                   roughness=0.04, height=None):
    """Reference shared scalar pixels with independently editable channel amounts.

    Color is multiplicative around the authored linear color; roughness is an
    additive amount. Height remains centered on 0.5, like procedural relief.
    """
    result = {"id": source_id, "scale": scale, "color": color,
              "roughness": roughness}
    if height is not None:
        result["height"] = height
    return result


def mask(kind, amount=0.35, scale=24.0, *, invert=False, contrast=None):
    result = {"kind": kind, "amount": amount, "scale": scale}
    if invert:
        result["invert"] = True
    if contrast is not None:
        result["contrast"] = contrast
    return result


def layer(name, color, roughness, metallic=0.0, *, procedural=None,
          scale=24.0, detail=0.12, height=None, mask=None, mask_effects=(),
          generated_source=None):
    result = {"name": name, "color": color, "roughness": roughness,
              "metallic": metallic, "scale": scale, "detail": detail}
    if procedural:
        result["procedural"] = procedural
    if height is not None:
        result["height"] = height
    if mask:
        result["mask"] = mask
    if mask_effects:
        result["mask_effects"] = list(mask_effects)
    if generated_source:
        result["generated_source"] = generated_source
    return result


def recipe(category, description, *layers, surface=None):
    result = {"category": category, "description": description, "layers": list(layers)}
    if surface:
        result["surface"] = surface
    return result


